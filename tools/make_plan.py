#!/usr/bin/env python3
"""Regenerates every plan artefact from tools/plan_data.py:
  docs/PLAN.md, docs/steps/SNN.md, the step table inside PROJECT_STATUS.md, docs/Pac-Man_PC_Port_Plan.html.
Run after changing a status:  python3 tools/make_plan.py"""
import os, json, re, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
import sys; sys.path.insert(0, HERE)
import plan_data as D

def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True); open(path, 'w').write(text)

RULES = [
 "One primary objective per step.",
 "Read only the files the step names. Do not re-read the whole project.",
 "Verify before extending: run the step's VERIFY. Code written is not a finished step.",
 "Never build on an unverified step. If S(n) fails, fix S(n) before S(n+1).",
 "Never redo VERIFIED work. Replacing working code needs a written reason plus regression tests.",
 "Checkpoint after every step: update PROJECT_STATUS.md, the plan status, evidence, known limits, next step.",
 "Keep each step small enough to finish inside one context. If it looks big, split it before starting.",
 "Spend tokens on inspecting, implementing, testing, fixing, documenting. No long tutorials.",
 "Do not ask the user technical questions. Investigate, choose the safest option, record the decision. Ask only for human decisions or information only the user has.",
 "Never claim success without evidence. 'It compiles' and 'a window opened' do not prove hardware is emulated correctly. Prefer exact comparison against the prototype oracle, ROM data, or documented arcade values.",
]
TEMPLATE_FIELDS = ["OBJECTIVE","WHY","STARTING STATE","READ FIRST","MAY TOUCH","IMPLEMENT","DO NOT","VERIFY","SUCCESS CRITERIA","IF FAILURE","DOCUMENT","CHECKPOINT"]
STD_PROMPT = ("Do STEP {id} ({name}). Read PROJECT_STATUS.md and docs/steps/{id}.md first, follow it exactly, "
              "do not redo verified steps, stop at the checkpoint, then update PROJECT_STATUS.md and the plan.")
RESUME = ("I'm continuing my Pac-Man arcade port. I've attached the latest project zip and my ROM. Read PROJECT_STATUS.md, "
          "do the step it names as Next step by following docs/steps/<that step>.md exactly, do not redo VERIFIED steps, "
          "run the tests, make the checkpoint zip, update the status and plan, and tell me in plain words what happened. "
          "Don't ask me technical questions; I'm not a programmer.")

def bullets(xs): return "\n".join(f"- {x}" for x in xs) if xs else "- (none)"
def step_md(st):
    sid = st['id']; u = st['user']
    return f"""# STEP {sid}: {st['name']}
Status: **{st['status']}**   Lane: {st['lane']}   Depends on: {', '.join(st['deps']) or 'nothing'}

OBJECTIVE: {st['obj']}

WHY: {st['why']}

STARTING STATE: {st['start']}

READ FIRST: {st['read']}

MAY TOUCH (only these): {st['touch']}

IMPLEMENT:
{bullets(st['do'])}

DO NOT:
{bullets(st['dont'])}

VERIFY:
{bullets(st['verify'])}

SUCCESS CRITERIA: {st['ok']}

IF FAILURE: {st['fail'].format(id=sid)}

DOCUMENT: {st['doc']}

EVIDENCE TO RECORD: {st['evidence'] or '-'}

CHECKPOINT: {st['cp'].format(id=sid)}
""" + (f"\nUSER ACTIONS (tell the user in plain click-by-click words; see the Standard test routine in the plan page):\n{bullets(u)}\n" if u else "")

def counts():
    c = collections.Counter(s['status'] for s in D.STEPS); return c

def plan_md():
    c = counts(); n = len(D.STEPS)
    rows = "\n".join(f"| {s['id']} | {s['lane']} | {s['name']} | {s['status']} | {', '.join(s['deps']) or '-'} |" for s in D.STEPS)
    old = "\n".join(f"| {a} | {b} |" for a, b in D.OLD_MAP)
    hist = "\n".join(f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in D.HISTORY)
    scr = "\n".join(f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in D.SCRAPPED)
    return f"""# Pac-Man PC Port Plan, version {D.PLAN_VERSION}
Authoritative roadmap. Generated by tools/make_plan.py from tools/plan_data.py. Do not hand-edit this file; edit the data file and regenerate.
The user-facing version is docs/Pac-Man_PC_Port_Plan.html (also published as an artifact).

## What the project is
{chr(10).join('- ' + x for x in D.SUMMARY)}

Approach, as it turned out: Track A built a C++ emulator of the board that ran the player's own ROM (S01 to S37, release 1.0), wrapped in a modern PC front end. Track B/C rewrote the main rules as readable C++ and made them switchable (T01, T02; release 1.1.0). Track D (N00 to N55) replaced the whole original program with native C++ proved identical frame by frame and removed the Z80 from the program (release 2.0.0). The ROM is never bundled; its data tables are read at run time. Modern features live outside the accuracy core.
Reference oracles: the Python prototype in tools/analysis (S05) and, since N50, the Z80 reference in tests/oracle. Every step is compared against one of them or against ROM data or documented arcade values.

Status now: {n} steps. {', '.join(f'{k} {v}' for k, v in c.items())}. Scrapped (removed or replaced, listed below): {len(D.SCRAPPED)}.

## Rules for every step
{chr(10).join(f'{i+1}. {r}' for i, r in enumerate(RULES))}

## Step template (each docs/steps/SNN.md follows it)
{', '.join(TEMPLATE_FIELDS)}. Plus: lane, dependencies, files the step may touch, evidence to record.

## Resuming after a context or token limit
Attach the latest project zip, then use this prompt:
> {RESUME}

Rollback: tools/checkpoint.sh SNN writes pacman-port_SNN.zip after every step. The newest zip with all tests passing is the last known-good state. Never delete the previous zip.

## How the project went
| Phase | When | Steps | What happened | Result |
|---|---|---|---|---|
{hist}

## Steps
| Step | Lane | Name | Status | Depends on |
|---|---|---|---|---|
{rows}

## Scrapped steps (removed or replaced; they are not in the table above)
| Step | Name | What happened | When | Why / what became of it |
|---|---|---|---|---|
{scr}

## Other changes of plan (nothing removed)
{chr(10).join(f'- {a}: {b}' for a, b in D.PLAN_CHANGES)}

## Old plan to new plan
| Old phase | New steps |
|---|---|
{old}
"""

def status_table():
    rows = "\n".join(f"| {s['id']} | {s['name']} | {s['status']} | {', '.join(s['deps']) or '-'} | {s['evidence'] or '-'} |" for s in D.STEPS)
    return "| Step | Name | Status | Depends on | Evidence |\n|---|---|---|---|---|\n" + rows

def update_status_file():
    p = os.path.join(ROOT, 'PROJECT_STATUS.md')
    if not os.path.exists(p): return
    t = open(p).read(); a, b = '<!-- STEPS-BEGIN -->', '<!-- STEPS-END -->'
    if a in t and b in t:
        t = re.sub(re.escape(a) + r'.*?' + re.escape(b), a + '\n' + status_table() + '\n' + b, t, flags=re.S)
        open(p, 'w').write(t)

def html():
    data = dict(version=D.PLAN_VERSION, lanes=D.LANES, steps=[{**s, 'fail': s['fail'].format(id=s['id']), 'cp': s['cp'].format(id=s['id']),
                'prompt': STD_PROMPT.format(id=s['id'], name=s['name'])} for s in D.STEPS],
                old=D.OLD_MAP, summary=D.SUMMARY, history=D.HISTORY, scrapped=D.SCRAPPED, changes=D.PLAN_CHANGES, quirks=D.QUIRKS, sources=D.SOURCES, rules=RULES, fields=TEMPLATE_FIELDS, resume=RESUME)
    tpl = open(os.path.join(HERE, 'plan_template.html')).read()
    return tpl.replace('__DATA__', json.dumps(data, ensure_ascii=False).replace('</', '<\\/'))

def main():
    w(os.path.join(ROOT, 'docs', 'PLAN.md'), plan_md())
    for s in D.STEPS: w(os.path.join(ROOT, 'docs', 'steps', f"{s['id']}.md"), step_md(s))
    update_status_file()
    out = html(); w(os.path.join(ROOT, 'docs', 'Pac-Man_PC_Port_Plan.html'), out)
    print(f"plan v{D.PLAN_VERSION}: {len(D.STEPS)} steps, {dict(counts())}; html {len(out)//1024} KB")
if __name__ == '__main__': main()
