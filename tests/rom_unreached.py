#!/usr/bin/env python3
"""N05: lists every ROM instruction that no coverage player executes, with the reason and the decision from tests/rom_unreached_reasons.txt, and writes
docs/notes/rom_unreached.md (addresses and words only, no ROM bytes). Exit 1 if an unreached instruction has no reason, or a reason range holds no unreached
instruction (a stale line), or two reason ranges overlap.
Usage: python3 tests/rom_unreached.py OUT.md COVERAGE_FILE..."""
import re, sys, bisect, collections

def load_cov(path):
    s = set()
    for ln in open(path):
        if ln.startswith('#') or not ln.strip(): continue
        a, b = ln.split(); s.update(range(int(a, 16), int(b, 16) + 1))
    return s

def main():
    out, files = sys.argv[1], sys.argv[2:]
    raw = set()
    for f in files: raw |= load_cov(f)
    ins = []; cur = None
    for ln in open('docs/disasm/pacman.asm'):
        mb = re.match(r"; BLOCK '(\w+?)(\d+)'", ln)
        if mb: cur = mb.group(1); continue
        mi = re.match(r'\t([a-z]+[^;]*?)\s*;([0-9a-f]{4})\s*$', ln)
        if mi and cur == 'code': ins.append(int(mi.group(2), 16))
    covered = set()
    for a in raw:                       # prefix bytes (DD, FD, ED, CB) are run as their own step: folded into their instruction (see rom_map.py)
        i = bisect.bisect_right(ins, a) - 1
        if i >= 0 and a - ins[i] <= 3: covered.add(ins[i])
    un = [a for a in ins if a not in covered]
    reasons = []
    for ln in open('tests/rom_unreached_reasons.txt'):
        if ln.startswith('#') or not ln.strip(): continue
        rng, cls, why, dec = [x.strip() for x in ln.split('|')]
        lo, hi = [int(x, 16) for x in rng.split('-')]
        reasons.append((lo, hi, cls, why, dec))
    problems = []
    for i, r in enumerate(reasons):
        for q in reasons[i + 1:]:
            if r[0] <= q[1] and q[0] <= r[1]: problems.append('reason ranges overlap: %04X-%04X and %04X-%04X' % (r[0], r[1], q[0], q[1]))
    per = collections.defaultdict(list)
    for a in un:
        hit = [r for r in reasons if r[0] <= a <= r[1]]
        if not hit: problems.append('unreached instruction %04X has no reason' % a)
        else: per[hit[0][:2]].append(a)
    for r in reasons:
        if (r[0], r[1]) not in per: problems.append('stale reason %04X-%04X: every instruction in it is executed now' % (r[0], r[1]))
    n_total, n_un = len(ins), len(un)
    L = ['# ROM instructions that no coverage player executes (generated by tests/rom_unreached.py, step N05; the reasons are in tests/rom_unreached_reasons.txt)', '',
         'Addresses and words only; no ROM bytes. Coverage: the S27 replay and the T01a player (N01) and the coverage players A, B, C (N02 to N04, extended in N05) and the service-switch player D (N05).', '',
         'Result: %d of %d instructions are executed (%.1f percent). %d are not; every one of them is listed below with a reason and a decision.' % (n_total - n_un, n_total, 100.0 * (n_total - n_un) / n_total, n_un), '',
         'Decision words: PORT = the native game contains it; it is proved either by a play situation or, when no situation reaches it, by the isolated random-state test of its routine (as in T02b to T02h). LEAVE OUT = the native game does not contain it (dead code). N47 = decided in step N47 (power-on self test). PORT AS DATA = it is data, not code.', '']
    L.append('## Summary by decision')
    d = collections.Counter()
    for lo, hi, cls, why, dec in reasons: d[re.split(r'[;(]', dec)[0].strip()] += len(per.get((lo, hi), []))
    for k, v in sorted(d.items()): L.append('- %s: %d instructions' % (k, v))
    L += ['', '## The groups', '| First | Last | Instructions | Kind | Reason | Decision |', '|---|---|---|---|---|---|']
    for lo, hi, cls, why, dec in reasons:
        L.append('| %04X | %04X | %d | %s | %s | %s |' % (lo, hi, len(per.get((lo, hi), [])), cls, why, dec))
    open(out, 'w').write('\n'.join(L) + '\n')
    print('instructions %d, executed %d (%.1f%%), not executed %d in %d groups' % (n_total, n_total - n_un, 100.0 * (n_total - n_un) / n_total, n_un, len(reasons)))
    for p in problems: print('FAIL:', p)
    return 1 if problems else 0

sys.exit(main())
